# frozen_string_literal: true

# Builds po/org.rubygtkproject.Biblioteca.pot from the files listed in
# POTFILES.in.
#
# Upstream has no po/ at all: src/biblioteca says "We do not support
# translations", and meson.build calls no i18n module, so there is no upstream
# extractor to port. This stands in for the `xgettext` invocation an i18n-aware
# GNOME project would have, over the four kinds of file this port marks strings
# in:
#
#   *.rb              `_('...')` and `_("...")`
#   *.ui              <property ... translatable="yes">
#   *.desktop         the keys listed in DESKTOP_KEYS
#   *.metainfo.xml    <summary>, <caption>, and <p>/<li> under <description>
#
# `rxgettext` from the gettext gem covers the first of those and none of the
# other three, which is why this is one script rather than a GetText::Tools
# task. The two XML formats are matched with regexps rather than parsed,
# because rexml is a bundled gem this port does not depend on and both shapes
# are generated by this repository.

ROOT = File.expand_path('..', __dir__)
DOMAIN = 'org.rubygtkproject.Biblioteca'
PACKAGE = 'Biblioteca'
POT = File.join(__dir__, "#{DOMAIN}.pot")

# data/app.desktop marks Name and Keywords "TRANSLATORS: Don't translate".
DESKTOP_KEYS = %w[Comment].freeze

RUBY_MARKER = /(?<![A-Za-z0-9_])_\(\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*\)/

def unescape_ruby(literal) = literal.gsub(/\\(.)/) { Regexp.last_match(1) }

def from_ruby(source)
  source.to_enum(:scan, RUBY_MARKER).map do
    Regexp.last_match.then do |match|
      [unescape_ruby(match[1] || match[2]), source[0...match.begin(0)].count("\n") + 1]
    end
  end
end

UI_MARKER = /<property\s+name="[^"]*"\s+translatable="yes"\s*>(.*?)<\/property>/m

def unescape_xml(text)
  text.gsub('&lt;', '<').gsub('&gt;', '>').gsub('&quot;', '"')
      .gsub('&apos;', "'").gsub('&amp;', '&')
end

def from_ui(source)
  source.to_enum(:scan, UI_MARKER).map do
    Regexp.last_match.then do |match|
      [unescape_xml(match[1]), source[0...match.begin(0)].count("\n") + 1]
    end
  end
end

def from_desktop(source)
  source.lines.each_with_index.filter_map do |line, index|
    line.split('=', 2).then do |key, value|
      if DESKTOP_KEYS.include?(key) && value
        [value.chomp, index + 1]
      end
    end
  end
end

# <summary> and <caption> stand alone; <p> and <li> are only translatable
# inside <description>, and the <description translatable="no"> blocks under
# <releases> are skipped for that reason.
METAINFO_STANDALONE = %r{<(summary|caption)\s*>(.*?)</\1>}m
METAINFO_DESCRIPTION = %r{<description\s*>(.*?)</description>}m
METAINFO_PARAGRAPH = %r{<(p|li)\s*>(.*?)</\1>}m

def from_metainfo(source)
  [
    *source.scan(METAINFO_STANDALONE).map { |_, text| text },
    *source.scan(METAINFO_DESCRIPTION).flat_map do |description,|
      description.scan(METAINFO_PARAGRAPH).map { |_, text| text }
    end,
  ].map { |text| [unescape_xml(text).strip.gsub(/\s+/, ' '), nil] }
end

def extract(path)
  File.read(File.join(ROOT, path)).then do |source|
    case File.extname(path)
    when '.rb' then from_ruby(source)
    when '.ui' then from_ui(source)
    when '.desktop' then from_desktop(source)
    else from_metainfo(source)
    end
  end
end

def escape_po(msgid)
  msgid.gsub('\\', '\\\\\\\\').gsub('"', '\"')
end

messages = {}
File.readlines(File.join(__dir__, 'POTFILES.in'), chomp: true)
    .reject { |line| line.empty? || line.start_with?('#') }
    .each do |path|
      extract(path).each do |msgid, line|
        unless msgid.empty?
          messages[msgid] ||= []
          messages[msgid] << [path, line].compact.join(':')
        end
      end
    end

File.open(POT, 'w') do |pot|
  pot.puts <<~HEADER
    # Message catalogue template for #{PACKAGE}.
    # Generated by po/extract.rb from po/POTFILES.in; do not edit by hand.
    #
    msgid ""
    msgstr ""
    "Project-Id-Version: #{PACKAGE}\\n"
    "Report-Msgid-Bugs-To: https://biblioteca.sonny.re/feedback\\n"
    "MIME-Version: 1.0\\n"
    "Content-Type: text/plain; charset=UTF-8\\n"
    "Content-Transfer-Encoding: 8bit\\n"
    "Language: \\n"
  HEADER

  messages.each do |msgid, locations|
    pot.puts
    locations.each { |location| pot.puts "#: #{location}" }
    pot.puts %(msgid "#{escape_po(msgid)}")
    pot.puts 'msgstr ""'
  end
end

puts "#{messages.size} messages written to #{POT.delete_prefix("#{ROOT}/")}"
